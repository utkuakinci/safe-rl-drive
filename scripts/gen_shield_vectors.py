"""Generate cross-language conformance vectors for the safety shield (Python reference -> C++ gtest).

Mixes safety observations recorded from real highway-env / merge / intersection rollouts with
synthetic edge cases, and stores the Python shield's decision for every action.

    python scripts/gen_shield_vectors.py --out ros2_ws/src/rl_policy_node/test/shield_vectors.csv
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from safe_rl_drive.safety.observer import SAFETY_FEATS, SAFETY_HEADER, SAFETY_K, safety_observation
from safe_rl_drive.safety.shield import SafetyShield


def synthetic(rng: np.random.Generator, n: int) -> list[np.ndarray]:
    out = []
    for _ in range(n):
        x = np.zeros(SAFETY_HEADER + SAFETY_K * SAFETY_FEATS, dtype=np.float32)
        x[0] = rng.uniform(0, 32)
        x[1:3] = rng.random(2) < 0.7
        for i in range(rng.integers(0, SAFETY_K + 1)):
            b = SAFETY_HEADER + i * SAFETY_FEATS
            lane = rng.choice([-2, -1, 0, 1, 2])
            x[b : b + 5] = (
                1.0,
                rng.uniform(-40, 60),
                lane * 4.0 + rng.normal(0, 0.8),
                rng.uniform(-15, 8),
                rng.normal(0, 1.5),
            )
        out.append(x)
    return out


def recorded(
    scenarios=("highway", "merge", "intersection"), steps: int = 60, seed: int = 0
) -> list[np.ndarray]:
    from safe_rl_drive.envs.factory import make_env

    rng = np.random.default_rng(seed)
    out = []
    for sc in scenarios:
        env = make_env(sc, seed=seed)
        env.reset(seed=seed)
        for _ in range(steps):
            out.append(safety_observation(env.unwrapped))
            _, _, term, trunc, _ = env.step(int(rng.integers(0, 5)))
            if term or trunc:
                env.reset()
    return out


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--out", type=Path, default=Path("ros2_ws/src/rl_policy_node/test/shield_vectors.csv"))
    p.add_argument("--synthetic", type=int, default=300)
    p.add_argument("--no-recorded", action="store_true")
    a = p.parse_args(argv)
    rng = np.random.default_rng(0)
    obs = synthetic(rng, a.synthetic) + ([] if a.no_recorded else recorded())
    shield = SafetyShield()
    lines = [
        "# action,expected_final,expected_aeb,safety_obs[...] (generated by scripts/gen_shield_vectors.py)"
    ]
    for x in obs:
        vals = ",".join(f"{v:.6g}" for v in x)
        x = np.array([float(v) for v in vals.split(",")], dtype=np.float32)  # decide on what C++ will read
        for action in range(5):
            d = shield.filter(action, x)
            lines.append(f"{action},{d.final},{int(d.aeb)},{vals}")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 1} vectors -> {a.out}")


if __name__ == "__main__":
    main()
